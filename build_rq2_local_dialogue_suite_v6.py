def _dedup(values: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out


def _auto_keys(value: str) -> list[str]:
    keys = [value]
    if value.endswith(" am") or value.endswith(" pm"):
        keys.append(value.split()[0])
    if value.startswith("room "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("table "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("platform "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("window "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("gate "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("locker "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("slot "):
        keys.append(value.split(" ", 1)[1])
    if value.startswith("extension "):
        keys.append(value.split(" ", 1)[1])
    return _dedup(keys)


