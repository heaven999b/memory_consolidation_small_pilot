def _upgrade_base_items(items: list[dict[str, object]]) -> list[dict[str, object]]:
    upgraded: list[dict[str, object]] = []
    for item in items:
        row = dict(item)
        row.setdefault("memory_rumor_templates", DEFAULT_LOCAL_DIALOGUE_RUMOR_TEMPLATES)
        prelude = list(row.get("memory_prelude_lines", []))
        if len(prelude) < 3:
            prelude.append(
                f"[CHAT LOG] Follow-up: Just so nobody swaps it later, {row['thing']} = {row['true_v']}, not {row['false_v']}."
            )
        row["memory_prelude_lines"] = prelude
        upgraded.append(row)
    return upgraded


def main() -> None:
    base_items = json.loads(BASE_PATH.read_text(encoding="utf-8"))
    merged = _upgrade_base_items(base_items) + EXTRA_ITEMS
    if len(merged) != 100:
        raise SystemExit(f"Expected 100 items, got {len(merged)}")
    OUTPUT_PATH.write_text(json.dumps(merged, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")
    print(f"n_items={len(merged)}")


if __name__ == "__main__":
    main()
